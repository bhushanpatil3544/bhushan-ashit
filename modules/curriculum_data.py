def get_specialized_content(topic_id, item):
    name = item['topicName']
    sub = item['subjectName']
    chap = item['chapterName']
    exam = item['examName']

    # Match topic patterns
    if "vedic" in topic_id:
        from modules.data_history import get_history_modules
        hist = get_history_modules()
        if topic_id in hist: return hist[topic_id]
    elif "religions" in topic_id:
        from modules.data_history import get_history_modules
        hist = get_history_modules()
        if topic_id in hist: return hist[topic_id]

    # Specific Builders by Domain
    if "mpsc-hist" in topic_id:
        return build_history_topic(topic_id, name, chap)
    elif "mpsc-polity" in topic_id:
        return build_polity_topic(topic_id, name, chap)
    elif "mpsc-geo" in topic_id:
        return build_geography_topic(topic_id, name, chap)
    elif "mpsc-eco" in topic_id:
        return build_economy_topic(topic_id, name, chap)
    elif "mpsc-sci" in topic_id:
        return build_science_topic(topic_id, name, chap)
    elif "mpsc-env" in topic_id:
        return build_environment_topic(topic_id, name, chap)
    elif "mpsc-mar" in topic_id:
        return build_marathi_topic(topic_id, name, chap)
    elif "mpsc-eng" in topic_id:
        return build_english_topic(topic_id, name, chap)
    elif "mpsc-ca" in topic_id or "rrb-ga" in topic_id:
        return build_ga_ca_topic(topic_id, name, chap, exam)
    elif "rrb-math" in topic_id:
        return build_math_topic(topic_id, name, chap)
    elif "rrb-reasoning" in topic_id or "mpsc-reas" in topic_id:
        return build_reasoning_topic(topic_id, name, chap)
    else:
        return build_general_topic(topic_id, name, chap, sub, exam)

